-- ==========================================
-- PROPUESTA SQL MINIMA PARA INTEGRAR ORDENES DE TRABAJO CON COTIZACIONES
-- (PostgreSQL 17) — SOLO PROPUESTA, NO EJECUTADA
-- ==========================================
-- Contexto:
--   * evaluaciones_orden_trabajo hoy guarda solo diagnostico, trabajo_propuesto
--     y observaciones. No existe forma de persistir los materiales/repuestos.
--   * cotizaciones.id_evaluacion es una FK exclusiva de evaluaciones_visita_tecnica
--     y su columna origen esta limitada por CHECK a ('DIRECTA','EVALUACION').
--   * No es posible vincular una evaluacion de orden con una cotizacion sin
--     ampliar el esquema.
--
-- Las sentencias siguientes cubren SOLO lo minimo necesario para:
--   1) almacenar materiales/repuestos de la evaluacion de una orden;
--   2) asociar dicha evaluacion (pendiente de cotizar) con una cotizacion;
--   3) permitir que la cotizacion creada desde la evaluacion de orden use el
--      estado real 'EN PROCESO' del modulo existente.
--
-- Autorizacion pendiente del usuario antes de aplicar en PostgreSQL.

BEGIN;

-- ==========================================
-- 1. MATERIALES / REPUESTOS DE LA EVALUACION DE ORDEN
-- ==========================================
-- Espejo de evaluacion_visita_materiales para NO reutilizar indebidamente la
-- relacion de Visitas. Cada detalle pertenece a una evaluacion de orden.
CREATE TABLE IF NOT EXISTS public.evaluacion_orden_trabajo_materiales (
    id_detalle     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion  INTEGER NOT NULL,
    descripcion    VARCHAR(200) NOT NULL,
    cantidad       NUMERIC(10, 2) NOT NULL,
    unidad         VARCHAR(30),

    CONSTRAINT fk_eval_orden_material_evaluacion
        FOREIGN KEY (id_evaluacion)
        REFERENCES public.evaluaciones_orden_trabajo(id_evaluacion)
        ON DELETE CASCADE,

    CONSTRAINT ck_eval_orden_material_cantidad CHECK (cantidad > 0)
);

-- ==========================================
-- 2. VINCULO EVALUACION DE ORDEN -> COTIZACION
-- ==========================================
-- Nueva columna opcional en cotizaciones; una cotizacion puede nacer de una
-- visita (id_evaluacion) o de una orden (id_evaluacion_orden), no de ambas.
-- La unicidad garantiza una sola cotizacion por evaluacion de orden.
ALTER TABLE public.cotizaciones
    ADD COLUMN IF NOT EXISTS id_evaluacion_orden INTEGER NULL;

ALTER TABLE public.cotizaciones
    ADD CONSTRAINT fk_cotizaciones_evaluacion_orden
        FOREIGN KEY (id_evaluacion_orden)
        REFERENCES public.evaluaciones_orden_trabajo(id_evaluacion)
        ON DELETE RESTRICT;

-- PostgreSQL permite multiples NULL en restricciones UNIQUE.
ALTER TABLE public.cotizaciones
    ADD CONSTRAINT uq_cotizaciones_evaluacion_orden
        UNIQUE (id_evaluacion_orden);

-- ==========================================
-- 3. NUEVO ORIGEN 'ORDEN_TRABAJO'
-- ==========================================
-- Los nombres de constraint siguen las convenciones del modelo SQLAlchemy
-- existente (verificar su existencia real en PostgreSQL antes de aplicar).
ALTER TABLE public.cotizaciones
    DROP CONSTRAINT IF EXISTS ck_cotizaciones_origen;

ALTER TABLE public.cotizaciones
    ADD CONSTRAINT ck_cotizaciones_origen
        CHECK (origen IN ('DIRECTA', 'EVALUACION', 'ORDEN_TRABAJO'));

-- Exige exactamente una entidad fuente segun el origen de la cotizacion.
ALTER TABLE public.cotizaciones
    DROP CONSTRAINT IF EXISTS ck_cotizaciones_origen_evaluacion;

ALTER TABLE public.cotizaciones
    ADD CONSTRAINT ck_cotizaciones_origen_evaluacion CHECK (
        (origen = 'DIRECTA' AND id_evaluacion IS NULL AND id_evaluacion_orden IS NULL)
        OR (origen = 'EVALUACION' AND id_evaluacion IS NOT NULL AND id_evaluacion_orden IS NULL)
        OR (origen = 'ORDEN_TRABAJO' AND id_evaluacion IS NULL AND id_evaluacion_orden IS NOT NULL)
    );

COMMIT;

-- ==========================================
-- RELACIONES RESULTANTES (resumen)
-- ==========================================
-- evaluaciones_orden_trabajo (1) ---< evaluacion_orden_trabajo_materiales (N)
--      |                                          (diagnostico, trabajo_propuesto,
--      |                                           materiales, observaciones)
--      v
-- cotizaciones (1) ----< cotizacion_detalles (N)
--      -- id_evaluacion_orden (opcional, unico) -> evaluaciones_orden_trabajo
--      -- origen 'ORDEN_TRABAJO' identifica el flujo para la interfaz; el origen
--         VISIBLE (tipo de trabajo) se toma de tipos_trabajo por la orden.
--      -- La proforma existente se reutiliza sin cambios (1:1 con la cotizacion
--         ACEPTADA).

-- IMPLEMENTACION DE PENDIENTES (SOLO DESPUES DE AUTORIZAR ESTA MIGRACION):
--   * evaluacion de orden: guardar materiales y marcarla como pendiente de cotizar
--     (la existencia de la evaluacion sin id_evaluacion_orden define el pendiente).
--   * terreno de cotizaciones: listado de pendientes (Origen = tipo de trabajo),
--     creacion con estado 'EN PROCESO' precargando cliente, trabajo propuesto,
--     materiales, cantidades y unidades; el administrador asigna precios.
--   * una vez cotizada (id_evaluacion_orden != NULL), bloquear la edicion de la
--     evaluacion de la orden (aprobacion comercial real).